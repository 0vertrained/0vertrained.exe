#!/usr/bin/env node
// Compiles src/design/tokens.json (the Chalk & Brass design system, copied
// verbatim from the design-system artifact) into src/design/tokens.css:
// every colour, spacing, radius, shadow, z-index and size token becomes a
// custom property, the two font stacks become --font-mono / --font-sans, and
// each font file gets an @font-face with font-display: swap. The dark theme
// is :root; the light theme is [data-theme="light"] on <html>. Type styles
// are not emitted: src/design/kit.css carries them as the .ot-* classes.
// tokens.test.ts fails when this file is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const tokens = JSON.parse(readFileSync(here("../src/design/tokens.json"), "utf8"));

export function compileTokens(t) {
  const themes = t.color.themes.map((x) => x.id);
  const [primary, ...others] = themes;
  const valueFor = (token, theme) => (typeof token.value === "string" ? token.value : token.value[theme] ?? token.value[primary]);
  const families = ["spacing", "radius", "shadow", "zIndex", "size"].filter((f) => t[f]);
  const lines = [];
  lines.push("/* GENERATED by scripts/gen-tokens.mjs from src/design/tokens.json. Do not edit; edit tokens.json and run `npm run gen:tokens`. */");
  for (const f of t.type.fonts) {
    lines.push(`@font-face { font-family: "${f.family}"; font-style: ${f.style ?? "normal"}; font-weight: ${f.weight}; font-display: swap; src: url("./${f.file}") format("woff2"); }`);
  }
  lines.push(":root {");
  lines.push("  color-scheme: dark;");
  for (const [k, v] of Object.entries(t.type.families)) lines.push(`  --font-${k}: ${v};`);
  for (const c of t.color.tokens) lines.push(`  --${c.name}: ${valueFor(c, primary)};`);
  for (const f of families) for (const x of t[f].tokens) lines.push(`  --${x.name}: ${typeof x.value === "string" ? x.value : valueFor(x, primary)};`);
  lines.push("}");
  for (const theme of others) {
    lines.push(`[data-theme="${theme}"] {`);
    lines.push(`  color-scheme: ${theme};`);
    for (const c of t.color.tokens) lines.push(`  --${c.name}: ${valueFor(c, theme)};`);
    for (const f of families) for (const x of t[f].tokens) if (typeof x.value !== "string") lines.push(`  --${x.name}: ${valueFor(x, theme)};`);
    lines.push("}");
  }
  return lines.join("\n") + "\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = compileTokens(tokens);
  if (process.argv.includes("--check")) {
    const current = readFileSync(here("../src/design/tokens.css"), "utf8");
    if (current !== css) {
      console.error("src/design/tokens.css is stale: run `npm run gen:tokens`.");
      process.exit(1);
    }
  } else {
    writeFileSync(here("../src/design/tokens.css"), css);
    console.log("wrote src/design/tokens.css");
  }
}
