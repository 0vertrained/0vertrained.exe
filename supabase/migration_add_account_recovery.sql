-- V13.4 account recovery rate limiting + append-only audit trail.
-- Both tables are intentionally service-role-only. The browser must never be
-- able to inspect usernames, attempt counters, or recovery event metadata.

create table if not exists public.account_recovery_attempts (
  username_hash text primary key,
  attempts integer not null default 0 check (attempts >= 0),
  window_started_at timestamptz not null default now(),
  lock_until timestamptz,
  updated_at timestamptz not null default now()
);

create table if not exists public.account_recovery_events (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  username_hash text not null,
  event_type text not null check (event_type in ('failed', 'rate_limited', 'succeeded')),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_account_recovery_events_created_at
  on public.account_recovery_events (created_at desc);
create index if not exists idx_account_recovery_events_username_hash
  on public.account_recovery_events (username_hash, created_at desc);

alter table public.account_recovery_attempts enable row level security;
alter table public.account_recovery_events enable row level security;

-- No anon/authenticated policies by design. Netlify's service role bypasses RLS.
revoke all on public.account_recovery_attempts from anon, authenticated;
revoke all on public.account_recovery_events from anon, authenticated;
